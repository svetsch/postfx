package io.postfx.io;

import io.postfx.BuildInfo;
import io.postfx.engine.ExecutionResult;
import io.postfx.engine.JsonUtil;
import io.postfx.engine.RequestPreparer;
import io.postfx.engine.RunReport;
import io.postfx.engine.TestResult;
import io.postfx.engine.UrlUtil;
import io.postfx.engine.VariableContext;
import io.postfx.model.Auth;
import io.postfx.model.AuthType;
import io.postfx.model.Body;
import io.postfx.model.Check;
import io.postfx.model.Collection;
import io.postfx.model.Environment;
import io.postfx.model.Extractor;
import io.postfx.model.Folder;
import io.postfx.model.Item;
import io.postfx.model.Items;
import io.postfx.model.KeyValue;
import io.postfx.model.OAuth2;
import io.postfx.model.RequestItem;

import java.time.LocalDateTime;
import java.time.format.DateTimeFormatter;
import java.util.ArrayList;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import java.util.regex.Matcher;
import java.util.regex.Pattern;

/**
 * Generates a Markdown test document from a collection: one test case per request with the request details and the
 * expected results (declarative checks and the names of pm.test assertions). With a {@link RunReport} the actual
 * results of a run are added, turning the document into a test report.
 */
public final class MarkdownExporter {
    private static final Pattern PM_TEST = Pattern.compile("pm\\.test\\(\\s*(['\"`])(.+?)\\1");
    private static final Pattern LEGACY_TEST = Pattern.compile("tests\\[\\s*(['\"`])(.+?)\\1\\s*]");
    private static final String MASK = "••••••";

    public static class Options {
        public Environment environment;
        public List<KeyValue> globals = new ArrayList<>();
        /** Include pre-request and test scripts as collapsible code blocks. */
        public boolean includeScripts = true;
        /** Add "- [ ]" check boxes and a result line to each test case (manual test execution). */
        public boolean checklist = true;
        /** Results of a run to show next to the expected results; null for a plain test plan. */
        public RunReport report;
    }

    private MarkdownExporter() {}

    public static String generate(Collection collection, Folder scope, Options o) {
        Folder root = scope == null ? collection : scope;
        StringBuilder md = new StringBuilder();
        String title = o.report != null ? "Test report" : "Test document";
        md.append("# ").append(title).append(": ").append(text(root.name)).append("\n\n");
        md.append("_Generated by PostFX ").append(BuildInfo.version()).append(" on ")
                .append(LocalDateTime.now().format(DateTimeFormatter.ofPattern("yyyy-MM-dd HH:mm"))).append(" · ")
                .append(scope == null || scope == collection ? "collection" : "folder of the collection " + text(collection.name))
                .append(o.environment != null ? " · environment **" + text(o.environment.name) + "**" : "")
                .append("_\n\n");
        if (root.description != null && !root.description.isBlank()) md.append(para(root.description)).append("\n\n");

        List<RequestItem> requests = Items.flatten(root);
        Map<RequestItem, String> ids = new LinkedHashMap<>();
        for (int i = 0; i < requests.size(); i++) ids.put(requests.get(i), String.format("TC-%02d", i + 1));

        if (o.report != null) runSummary(md, o.report);
        summary(md, collection, requests, ids, o);
        configuration(md, collection, o);

        md.append("## Test cases\n\n");
        VariableContext vars = VariableContext.of(workspaceWith(o.globals), collection, o.environment);
        writeItems(md, collection, root, root, ids, vars, o);
        return md.toString().replaceAll("\n{3,}", "\n\n");
    }

    private static io.postfx.model.Workspace workspaceWith(List<KeyValue> globals) {
        io.postfx.model.Workspace ws = new io.postfx.model.Workspace();
        if (globals != null) ws.globals.addAll(globals);
        return ws;
    }

    // ------------------------------------------------------------------ sections

    private static void runSummary(StringBuilder md, RunReport r) {
        md.append("## Run summary\n\n");
        md.append(r.success() ? "**✅ Passed**" : "**❌ Failed**").append(r.cancelled ? " (stopped)" : "").append("\n\n");
        md.append("| Requests | Failed requests | Tests passed | Tests failed | Avg response | Duration | Iterations |\n");
        md.append("|---:|---:|---:|---:|---:|---:|---:|\n");
        md.append("| ").append(r.totalRequests()).append(" | ").append(r.failedRequests()).append(" | ").append(r.passedTests())
                .append(" | ").append(r.failedTests()).append(" | ").append(r.averageResponseTime()).append(" ms | ")
                .append(r.durationMs).append(" ms | ").append(r.iterations).append(" |\n\n");
        for (String e : r.errors) md.append("> ⚠ ").append(text(e)).append("\n\n");
    }

    private static void summary(StringBuilder md, Collection c, List<RequestItem> requests, Map<RequestItem, String> ids, Options o) {
        md.append("## Summary\n\n");
        if (requests.isEmpty()) {
            md.append("_No requests._\n\n");
            return;
        }
        md.append("| ID | Test case | Method | Endpoint | Expected |").append(o.report != null ? " Result |" : "").append("\n");
        md.append("|---|---|---|---|---|").append(o.report != null ? "---|" : "").append("\n");
        for (RequestItem r : requests) {
            List<String> expected = expectedSummary(r);
            md.append("| [").append(ids.get(r)).append("](#").append(anchor(ids.get(r), r.name)).append(") | ")
                    .append(cell(path(c, r) + r.name)).append(" | `").append(r.request.method).append("` | `")
                    .append(cell(r.request.url)).append("` | ").append(cell(expected.isEmpty() ? "—" : String.join("; ", expected))).append(" |");
            if (o.report != null) md.append(" ").append(resultIcon(results(o.report, r))).append(" |");
            md.append("\n");
        }
        md.append("\n");
    }

    private static void configuration(StringBuilder md, Collection c, Options o) {
        md.append("## Configuration\n\n");
        List<KeyValue> vars = new ArrayList<>();
        addVars(vars, o.globals, "global");
        addVars(vars, c.variables, "collection");
        if (o.environment != null) addVars(vars, o.environment.values, "environment");
        if (!vars.isEmpty()) {
            md.append("### Variables\n\n| Variable | Value | Scope |\n|---|---|---|\n");
            for (KeyValue kv : vars) {
                md.append("| `").append(cell(kv.key)).append("` | ")
                        .append("secret".equals(kv.type) || looksSecret(kv.key) ? MASK : "`" + cell(kv.value) + "`")
                        .append(" | ").append(kv.description).append(" |\n");
            }
            md.append("\n");
        }
        md.append("### Authentication\n\n").append(describeAuth(c.auth, false)).append("\n\n");
        if (o.includeScripts) {
            script(md, "Pre-request script run before every request", c.preRequestScript);
            script(md, "Test script run after every request", c.testScript);
            List<String> collectionTests = testNames(c.testScript);
            if (!collectionTests.isEmpty()) {
                md.append("Every test case also expects: ").append(String.join(", ", collectionTests.stream().map(t -> "*" + text(t) + "*").toList())).append("\n\n");
            }
        }
    }

    private static void addVars(List<KeyValue> out, List<KeyValue> vars, String scope) {
        if (vars == null) return;
        for (KeyValue kv : vars) {
            if (!kv.enabled || kv.key == null || kv.key.isBlank()) continue;
            KeyValue copy = new KeyValue(kv.key, kv.value);
            copy.type = kv.type;
            copy.description = scope;
            out.add(copy);
        }
    }

    private static void writeItems(StringBuilder md, Collection c, Folder root, Folder folder, Map<RequestItem, String> ids,
                                   VariableContext vars, Options o) {
        for (Item item : folder.items) {
            if (item instanceof Folder f) {
                md.append("### ").append(text(path(c, f) + f.name)).append("\n\n");
                if (f.description != null && !f.description.isBlank()) md.append(para(f.description)).append("\n\n");
                if (f.auth != null && f.auth.type != AuthType.INHERIT) md.append("Authentication for this folder: ").append(describeAuth(f.auth, false)).append("\n\n");
                if (o.includeScripts) {
                    script(md, "Folder pre-request script", f.preRequestScript);
                    script(md, "Folder test script", f.testScript);
                }
                writeItems(md, c, root, f, ids, vars, o);
            } else if (item instanceof RequestItem r) {
                testCase(md, c, r, ids.get(r), vars, o);
            }
        }
    }

    private static void testCase(StringBuilder md, Collection c, RequestItem r, String id, VariableContext vars, Options o) {
        md.append("#### ").append(id).append(" · ").append(text(r.name)).append("\n\n");
        if (r.description != null && !r.description.isBlank()) md.append(para(r.description)).append("\n\n");

        // ---- request
        md.append("**Request**\n\n| | |\n|---|---|\n");
        md.append("| Method | `").append(r.request.method).append("` |\n");
        md.append("| URL | `").append(cell(r.request.url)).append("` |\n");
        if (o.environment != null) {
            String resolved = vars.resolve(RequestPreparer.applyPathVariables(r.request.url, r.request.pathVariables));
            if (!resolved.equals(r.request.url)) md.append("| Resolved URL | `").append(cell(resolved)).append("` |\n");
        }
        List<io.postfx.model.Folder> chain = Items.ancestors(c, r).orElse(List.of(c));
        Auth auth = RequestPreparer.effectiveAuth(r.request, chain);
        md.append("| Authentication | ").append(cell((r.request.auth.type == AuthType.INHERIT && auth.type != AuthType.NONE ? "inherited: " : "")
                + describeAuth(auth, true))).append(" |\n\n");
        kvTable(md, "Path variables", r.request.pathVariables);
        kvTable(md, "Query parameters", UrlUtil.parseQuery(r.request.url));
        kvTable(md, "Headers", r.request.headers);
        body(md, r.request.body);
        if (o.includeScripts) script(md, "Pre-request script (setup)", r.preRequestScript);

        // ---- expected results
        md.append("**Expected results**\n\n");
        List<TestResult> actual = o.report == null ? null : results(o.report, r);
        List<String> lines = new ArrayList<>();
        for (Check ch : r.checks) {
            if (!ch.enabled) continue;
            lines.add(expectedLine(ch.describe(), "check", actual, o));
        }
        for (String t : testNames(r.testScript)) lines.add(expectedLine(t, "script", actual, o));
        if (lines.isEmpty()) lines.add((o.checklist && o.report == null ? "- [ ] " : "- ") + "The request succeeds (no assertion defined)");
        lines.forEach(l -> md.append(l).append('\n'));
        md.append('\n');
        if (o.includeScripts) script(md, "Test script", r.testScript);

        List<Extractor> extractors = r.extractors.stream().filter(e -> e.enabled && e.variable != null && !e.variable.isBlank()).toList();
        if (!extractors.isEmpty()) {
            md.append("**Values passed to the next test cases**\n\n| Variable | Source | Expression | Scope |\n|---|---|---|---|\n");
            for (Extractor e : extractors) {
                md.append("| `").append(cell(e.variable)).append("` | ").append(e.source.label).append(" | `")
                        .append(cell(e.expression == null ? "" : e.expression)).append("` | ").append(e.scope.label).append(" |\n");
            }
            md.append('\n');
        }

        // ---- actual result
        if (o.report != null) {
            actualResult(md, o.report, r);
        } else if (o.checklist) {
            md.append("**Result:** ☐ Pass ☐ Fail  \n**Tested by / date:** \n**Notes:** \n\n");
        }
        md.append("---\n\n");
    }

    private static String expectedLine(String name, String origin, List<TestResult> actual, Options o) {
        String label = text(name);
        if (actual == null) return (o.checklist ? "- [ ] " : "- ") + label;
        TestResult match = actual.stream().filter(t -> origin.equals(t.origin) && name.equals(t.name)).findFirst().orElse(null);
        if (match == null) return "- ➖ " + label + " _(not executed)_";
        if (match.skipped) return "- ➖ " + label + " _(skipped)_";
        return match.passed ? "- ✅ " + label : "- ❌ " + label + " — " + text(match.error == null ? "failed" : match.error);
    }

    private static void actualResult(StringBuilder md, RunReport report, RequestItem r) {
        List<ExecutionResult> runs = report.results.stream().filter(e -> r.id.equals(e.requestId)).toList();
        md.append("**Actual result**\n\n");
        if (runs.isEmpty()) {
            md.append("_Not executed in this run._\n\n");
            return;
        }
        md.append("| Iteration | Status | Time | Tests | Result |\n|---:|---|---:|---|---|\n");
        for (ExecutionResult e : runs) {
            String status = e.skipped ? "skipped" : e.response == null ? "not sent" : e.response.failed() ? cell(e.response.error)
                    : e.response.status + " " + e.response.statusText;
            md.append("| ").append(e.iteration + 1).append(" | ").append(status).append(" | ")
                    .append(e.response != null && !e.response.failed() ? e.response.timeMs + " ms" : "").append(" | ")
                    .append(e.passedCount()).append("/").append(e.tests.size()).append(" | ")
                    .append(e.passed() ? "✅" : "❌").append(" |\n");
        }
        md.append('\n');
        for (ExecutionResult e : runs) for (String err : e.errors) md.append("> ⚠ ").append(text(err)).append("\n\n");
    }

    // ------------------------------------------------------------------ helpers

    private static List<TestResult> results(RunReport report, RequestItem r) {
        List<TestResult> out = new ArrayList<>();
        report.results.stream().filter(e -> r.id.equals(e.requestId)).reduce((a, b) -> b).ifPresent(e -> out.addAll(e.tests));
        return out;
    }

    private static String resultIcon(List<TestResult> tests) {
        if (tests == null) return "";
        if (tests.isEmpty()) return "➖";
        return tests.stream().allMatch(t -> t.passed) ? "✅" : "❌";
    }

    private static List<String> expectedSummary(RequestItem r) {
        List<String> out = new ArrayList<>();
        int checks = 0;
        for (Check c : r.checks) {
            if (!c.enabled) continue;
            if (c.source == io.postfx.model.CheckSource.STATUS && c.operator == io.postfx.model.CheckOperator.EQUALS) out.add("status " + c.expected);
            else checks++;
        }
        int tests = testNames(r.testScript).size();
        if (checks > 0) out.add(checks + " check" + (checks > 1 ? "s" : ""));
        if (tests > 0) out.add(tests + " scripted test" + (tests > 1 ? "s" : ""));
        return out;
    }

    static List<String> testNames(String script) {
        List<String> out = new ArrayList<>();
        if (script == null) return out;
        Matcher m = PM_TEST.matcher(script);
        while (m.find()) out.add(m.group(2));
        m = LEGACY_TEST.matcher(script);
        while (m.find()) out.add(m.group(2));
        return out;
    }

    private static String path(Collection c, Item item) {
        StringBuilder sb = new StringBuilder();
        Items.ancestors(c, item).ifPresent(chain -> chain.stream().skip(1).forEach(f -> sb.append(f.name).append(" › ")));
        return sb.toString();
    }

    static String describeAuth(Auth a, boolean shortForm) {
        if (a == null) return "None";
        return switch (a.type) {
            case INHERIT -> "Inherited from the parent";
            case NONE -> "None";
            case BASIC -> "Basic, user `" + a.username + "`, password " + secret(a.password);
            case BEARER -> "Bearer token " + secret(a.token);
            case APIKEY -> "API key `" + a.apiKey + "` in the " + a.apiIn + ", value " + secret(a.apiValue);
            case OAUTH2, OIDC -> {
                OAuth2 o = a.oauth2;
                StringBuilder sb = new StringBuilder(a.type.label).append(", ").append(OAuth2.label(o.grantType));
                if (a.type == AuthType.OIDC && o.discoveryUrl != null && !o.discoveryUrl.isBlank()) sb.append(", provider `").append(o.discoveryUrl).append('`');
                if (!shortForm) {
                    if (o.accessTokenUrl != null && !o.accessTokenUrl.isBlank()) sb.append(", token URL `").append(o.accessTokenUrl).append('`');
                    if (o.clientId != null && !o.clientId.isBlank()) sb.append(", client `").append(o.clientId).append('`');
                    if (o.scope != null && !o.scope.isBlank()) sb.append(", scope `").append(o.scope).append('`');
                }
                yield sb.toString();
            }
        };
    }

    /** Shows variable references, hides literal secrets. */
    private static String secret(String value) {
        if (value == null || value.isBlank()) return "(empty)";
        return value.strip().matches("\\{\\{[^{}]+}}") ? "`" + value.strip() + "`" : MASK;
    }

    private static boolean looksSecret(String key) {
        String k = key.toLowerCase();
        return k.contains("password") || k.contains("secret") || k.contains("apikey") || k.contains("api_key") || k.endsWith("token");
    }

    private static void kvTable(StringBuilder md, String title, List<KeyValue> list) {
        List<KeyValue> enabled = list == null ? List.of() : list.stream().filter(kv -> kv.enabled && kv.key != null && !kv.key.isBlank()).toList();
        if (enabled.isEmpty()) return;
        md.append("*").append(title).append("*\n\n| Name | Value |\n|---|---|\n");
        for (KeyValue kv : enabled) {
            boolean hide = kv.key.equalsIgnoreCase("Authorization") || looksSecret(kv.key);
            md.append("| `").append(cell(kv.key)).append("` | ").append(hide ? secret(kv.value) : "`" + cell(kv.value) + "`").append(" |\n");
        }
        md.append('\n');
    }

    private static void body(StringBuilder md, Body b) {
        if (b == null) return;
        switch (b.mode) {
            case RAW -> {
                if (b.raw == null || b.raw.isBlank()) return;
                String lang = b.rawLanguage == null ? "" : b.rawLanguage;
                String content = "json".equals(lang) ? JsonUtil.prettyOrSame(b.raw) : "xml".equals(lang) ? io.postfx.engine.XmlUtil.prettyOrSame(b.raw) : b.raw;
                md.append("*Body (").append(lang.isEmpty() ? "text" : lang).append(")*\n\n").append(fence(content, lang)).append('\n');
            }
            case URLENCODED -> kvTable(md, "Body (x-www-form-urlencoded)", b.urlencoded);
            case FORMDATA -> {
                List<KeyValue> rows = new ArrayList<>();
                for (KeyValue kv : b.formdata) {
                    KeyValue copy = new KeyValue(kv.key, kv.isFile() ? "file: " + kv.value : kv.value, kv.enabled);
                    rows.add(copy);
                }
                kvTable(md, "Body (multipart form-data)", rows);
            }
            case GRAPHQL -> {
                md.append("*Body (GraphQL query)*\n\n").append(fence(b.graphqlQuery, "graphql")).append('\n');
                if (b.graphqlVariables != null && !b.graphqlVariables.isBlank()) md.append("*GraphQL variables*\n\n").append(fence(b.graphqlVariables, "json")).append('\n');
            }
            case BINARY -> md.append("*Body:* file `").append(b.binaryFile).append("`\n\n");
            default -> { }
        }
    }

    private static void script(StringBuilder md, String title, String code) {
        if (code == null || code.isBlank()) return;
        md.append("<details><summary>").append(title).append("</summary>\n\n").append(fence(code.strip(), "javascript")).append("\n</details>\n\n");
    }

    private static String fence(String content, String lang) {
        String c = content == null ? "" : content;
        String ticks = c.contains("```") ? "~~~~" : "```";
        return ticks + (lang == null ? "" : lang) + "\n" + c.stripTrailing() + "\n" + ticks + "\n";
    }

    /** Description text: single line breaks are kept (Markdown hard breaks). */
    static String para(String s) {
        return s.strip().replace("\r", "").replaceAll("(?<!\n)\n(?!\n)", "  \n");
    }

    /** Text for a table cell: no line breaks, escaped pipes. */
    static String cell(String s) {
        if (s == null) return "";
        return s.replace("\\", "\\\\").replace("|", "\\|").replace("\r", "").replace("\n", " ");
    }

    /** Plain text outside of tables: escape characters with a Markdown meaning at the start of words. */
    static String text(String s) {
        if (s == null) return "";
        return s.replace("\r", "").replace("\n", " ").replace("<", "&lt;").replace(">", "&gt;");
    }

    /** GitHub style anchor of a "#### TC-01 · Name" heading. */
    static String anchor(String id, String name) {
        String h = (id + " · " + name).toLowerCase();
        return h.replaceAll("[^\\p{L}\\p{N} _-]", "").trim().replace(' ', '-');
    }
}
